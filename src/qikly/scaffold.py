def _signature(fn):
    """A readable signature line for one top level function or class member."""
    args = []
    a = fn.args
    for i, arg in enumerate(a.args):
        text = arg.arg
        if arg.annotation is not None:
            try:
                text += f": {ast.unparse(arg.annotation)}"
            except Exception:
                pass
        args.append(text)
    if a.vararg:
        args.append("*" + a.vararg.arg)
    for arg in a.kwonlyargs:
        args.append(arg.arg)
    if a.kwarg:
        args.append("**" + a.kwarg.arg)
    if getattr(fn, "inherited", False):
        return f"{fn.name}(...)"
    sig = fn.name if getattr(fn, "attribute", False) else f"{fn.name}({', '.join(args)})"
    if fn.returns is not None:
        try:
            sig += f" -> {ast.unparse(fn.returns)}"
        except Exception:
            pass
    # The test agent never sees the code, so this is the only place it can
    # learn a call has to be awaited. Without it, trend-pulse's tools read as
    # plain functions and every generated test failed on correct code.
    # The same for a context manager: jsonl's open_stream raises only when
    # `with` enters it, so a test that just called it saw nothing.
    marks = _decorators(fn) if hasattr(fn, "decorator_list") else getattr(fn, "marks", set())
    # Not for an async context manager, which is entered with `async with`
    # and never awaited: `async` there told the agent to await it.
    if ((isinstance(fn, ast.AsyncFunctionDef) or getattr(fn, "is_async", False))
            and "asynccontextmanager" not in marks):
        sig = "async " + sig
    if "asynccontextmanager" in marks:
        sig += "  (a context manager: use it in an async with statement)"
    elif "contextmanager" in marks:
        sig += "  (a context manager: use it in a with statement)"
    return sig


def read_functions(source):
    """
    Top level public functions, in file order.

    Nested and underscore-prefixed functions are skipped: the interface block
    describes what tests may call, and a helper is not that.
    """
    tree = ast.parse(source)
    out = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if not node.name.startswith("_"):
                out.append(node)
    return out


class Member:
    """
    One line of a class's interface, shaped as a function node is, so the
    signature and the starter columns treat it as one: the constructor as
    `Name`, taking `__init__`'s arguments, or a method as `Name.method`. `self`
    or `cls` is already dropped, since a test never passes it.
    """

    def __init__(self, name, args, returns=None, attribute=False, owner=None,
                 inherited=False, is_async=False, marks=()):
        self.name, self.args, self.returns = name, args, returns
        self.attribute, self.owner, self.inherited = attribute, owner, inherited
        self.is_async, self.marks = is_async, set(marks)


def _decorators(node):
    names = set()
    for d in node.decorator_list:
        target = d.func if isinstance(d, ast.Call) else d
        names.add(target.attr if isinstance(target, ast.Attribute)
                  else getattr(target, "id", ""))
    return names


def _without_first(args, first=True):
    """
    `args` without its first positional argument, the instance or the class,
    and without any whose name starts with an underscore: iniconfig's
    constructor takes `_sections` and `_sources` for its own use, and a test
    written against them tests a detail, not the interface.
    """
    positional = list(args.posonlyargs) + list(args.args)
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    pairs = list(zip(positional, defaults))
    if first and pairs:
        pairs.pop(0)
    keep = [(a, d) for a, d in pairs if not a.arg.startswith("_")]
    kw = [(a, d) for a, d in zip(args.kwonlyargs, args.kw_defaults) if not a.arg.startswith("_")]
    # Defaults belong to the last arguments, so the kept ones still line up
    # once the leading arguments without one are left off the list.
    defaults = [d for _, d in keep]
    while defaults and defaults[0] is None:
        defaults.pop(0)
    return ast.arguments(posonlyargs=[], args=[a for a, _ in keep], vararg=args.vararg,
                         kwonlyargs=[a for a, _ in kw], kw_defaults=[d for _, d in kw],
                         kwarg=args.kwarg, defaults=defaults)


# Decorators that write an __init__ from the class's annotated fields.
_FIELD_CLASSES = {"dataclass", "define", "frozen", "mutable", "attrs", "s"}


def _generated_init(node):
    """
    The constructor arguments a dataclass-style decorator generates, or None.

    `@dataclass class Point: x: float; y: float = 0.0` has no `__init__` to
    read, and was described as `Point()`, a constructor taking nothing.
    """
    if not _decorators(node) & _FIELD_CLASSES:
        return None
    fields, defaults = [], []
    for item in node.body:
        if not (isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name)):
            continue
        annotation = ast.unparse(item.annotation)
        if annotation.startswith(("ClassVar", "typing.ClassVar")) or item.target.id.startswith("_"):
            continue
        value = item.value
        if (isinstance(value, ast.Call) and getattr(value.func, "attr", getattr(value.func, "id", ""))
                in ("field", "ib", "attrib") and any(
                    k.arg == "init" and isinstance(k.value, ast.Constant) and k.value.value is False
                    for k in value.keywords)):
            continue
        fields.append(ast.arg(arg=item.target.id, annotation=item.annotation))
        if value is not None:
            defaults.append(value)
        elif defaults:
            defaults = []
    return ast.arguments(posonlyargs=[], args=fields, vararg=None, kwonlyargs=[],
                         kw_defaults=[], kwarg=None, defaults=defaults)


def class_members(node):
    """
    The constructor and public methods of one class, in file order.

    The constructor comes first, with `__init__`'s arguments. A class with no
    `__init__` of its own and a base class inherits one this does not read, so
    it is written `Name(...)`: bidict's `bidict()` claimed it took nothing. A
    property is listed as an attribute, and other dunders are left out: what
    a test calls, not how Python reaches it.
    """
    init = next((n for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                 and n.name == "__init__"), None)
    empty = ast.arguments(posonlyargs=[], args=[], vararg=None, kwonlyargs=[],
                          kw_defaults=[], kwarg=None, defaults=[])
    generated = None if init else _generated_init(node)
    if init:
        args = _without_first(init.args)
    else:
        args = generated or empty
    out = [Member(node.name, args, owner=node.name,
                  inherited=init is None and generated is None and bool(node.bases))]
    for n in node.body:
        if not isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) or n.name.startswith("_"):
            continue
        marks = _decorators(n)
        if "overload" in marks:
            # A typing stub for one call shape; the real method follows it.
            continue
        name = f"{node.name}.{n.name}"
        if "property" in marks or "cached_property" in marks:
            out.append(Member(name, empty, n.returns, attribute=True, owner=node.name,
                              is_async=isinstance(n, ast.AsyncFunctionDef)))
        elif "setter" in marks or "deleter" in marks:
            continue
        else:
            args = _without_first(n.args, first="staticmethod" not in marks)
            out.append(Member(name, args, n.returns, owner=node.name,
                              is_async=isinstance(n, ast.AsyncFunctionDef), marks=marks))
    return out


def read_interface(source):
    """
    What tests may call, in file order: the public top level functions, and
    each public class as its constructor and public methods.

    A module made only of classes, such as iniconfig or bidict, used to be
    refused by `--scaffold` for having "no public top level functions", after
    `--score` had already raised questions about it.
    """
    out = []
    for node in top_definitions(ast.parse(source)):
        if isinstance(node, ast.ClassDef):
            out.extend(class_members(node))
        else:
            out.append(node)
    return out


def top_definitions(tree):
    """
    The module's public functions and classes, each under the name callers
    use, as Python binds them: a later binding of a name replaces an earlier
    one (`def parse` then `parse = _impl` is one entry, not two), and a name
    bound to a definition is that definition under the new name, whether
    written `EmailStr = _EmailStr` (msgspec-ext), `EmailStr: TypeAlias =
    _EmailStr`, `A = B = _impl`, or through another public alias. Order is
    each public name's last binding.
    """
    import copy
    defs, order = {}, []

    def bind(name, node):
        if name in order:
            order.remove(name)
        if not name.startswith("_"):
            order.append(name)
        defs[name] = node

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if "overload" not in _decorators(node):
                bind(node.name, node)
        elif isinstance(node, ast.ClassDef):
            bind(node.name, node)
        else:
            if isinstance(node, ast.Assign):
                targets, value = node.targets, node.value
            elif isinstance(node, ast.AnnAssign) and node.value is not None:
                targets, value = [node.target], node.value
            else:
                continue
            if isinstance(value, ast.Name) and value.id in defs:
                for target in targets:
                    if isinstance(target, ast.Name):
                        alias = copy.copy(defs[value.id])
                        alias.name = target.id
                        bind(target.id, alias)
    return [defs[name] for name in order]


def guess_entrypoint(functions, stem=None):
    """
    Which function runs the whole thing end to end.

    Prefers an explicit run_* name, then main, then whichever function takes
    the most arguments, on the reasoning that an end to end entry usually
    takes both an input and an output. It is a guess and the generated file
    says so.
    """
    names = [f.name for f in functions]
    plain = [f for f in functions if not isinstance(f, Member)]
    if not plain:
        # Only classes: a constructor, where every use starts. The class named
        # as the module is (IniConfig in iniconfig), else the one with the most
        # methods, else the first.
        classes = [f for f in functions if f.name == f.owner]
        if not classes:
            return None
        key = (stem or "").replace("_", "").lower()
        named = [c for c in classes if c.name.lower() == key]
        if named:
            return named[0]
        size = {c.name: sum(1 for f in functions if f.owner == c.name) for c in classes}
        return max(classes, key=lambda c: size[c.name])
    functions = plain
    for f in functions:
        if f.name.startswith("run_"):
            return f
    for f in functions:
        if f.name in ("main", "process", "execute"):
            return f
    return max(functions, key=lambda f: len(f.args.args)) if functions else None


def _relative_to(path, start):
    """
    `path` relative to `start`, or None when no relative path exists.

    On Windows there is no relative path between two drives, and
    os.path.relpath raises instead of answering. A module on D: scaffolded for a
    project on C: failed with "path is on mount 'D:', start on mount 'C:'",
    which is also how GitHub's Windows runners are laid out: the checkout on D:,
    temporary directories on C:.
    """
    try:
        return os.path.relpath(os.path.abspath(path), os.path.abspath(start))
    except ValueError:
        return None


def module_path(source_path, task_id):
    """
    The dotted path a run's tests import this module by.

    A run installs the implementation, seeded or generated, into
    outputs/agent_src/code/<task_id>/ under the file's own name, and runs pytest
    from the project root. So the module is outputs.agent_src.code.<task_id>.
    <file name>, wherever the original lives. It used to be the path relative
    to the project root, which made every test import the original file rather
    than the copy the coding agent patches, so no fix could ever reach a test.
    """
    stem = os.path.splitext(os.path.basename(source_path))[0]
    return "outputs.agent_src.code.%s.%s" % (task_id, importable(stem))


PLACEHOLDER_CRITERIA = '''acceptance_criteria:
  - "TODO: one checkable statement, with its boundary value, e.g. a humidity of
    100 is accepted and 101 is rejected"
'''


def with_questions(text, questions, written=None):
    """
    `text` with its placeholder criterion replaced by questions to answer, and
    whether the replacement was made.

    The questions are the ones `--score-code` raised about this file, each a
    comment above a TODO. Two checks before the result is used, because this
    writes into the section the whole tool rests on: the file must still parse,
    and none of the question text may survive the cut the coding agent's prompt
    is made from. Either failing keeps the plain scaffold.
    """
    import yaml

    from qikly import score_questions
    from qikly.agent_api.agent_interface import without_acceptance_criteria

    questions = [q for q in questions or []
                 if isinstance(q, dict) and isinstance(q.get("question"), str)]
    if not questions or text.count(PLACEHOLDER_CRITERIA) != 1:
        return text, False
    try:
        out = text.replace(PLACEHOLDER_CRITERIA,
                           score_questions.yaml_block(questions, written))
        criteria = (yaml.safe_load(out) or {}).get("acceptance_criteria")
        handed_over = without_acceptance_criteria(out)
        if not isinstance(criteria, list) or len(criteria) != len(questions):
            return text, False
        # A second guard: drop_question_lines has already removed every
        # line that starts with the mark, so this fires only if that failed.
        if score_questions._MARKED.search(handed_over) or any(
                q["question"][:40] in handed_over for q in questions):
            return text, False
    except Exception:
        return text, False
    return out, True


def importable(stem):
    """
    A file stem as a name Python can import: `my-calc` becomes `my_calc`.

    A dash, a space or a leading digit is fine in a filename and not in an
    import, so `--scaffold my-calc.py` used to write a module path no test
    could import. A run copies a seeded file in under this same name, so the
    path and the file agree, and the original file keeps its own name.
    """
    import keyword
    import re

    name = re.sub(r"\W", "_", stem) or "module"
    if name[0].isdigit():
        name = "_" + name
    if keyword.iskeyword(name):
        name += "_"
    return name


# A name part that means the argument is given a file rather than a value.
# Whole parts of the name, split on underscores: matched as substrings these
# caught `direction`, `fps`, `offpeak_rate` and `profile_id`.
_FILE_PARTS = {"path", "paths", "file", "files", "filename", "fname", "dir",
               "dirs", "directory", "folder", "fp", "csv", "tsv", "json",
               "stream", "url", "uri", "filepath", "infile", "dirpath"}
# With one of these as well, it is where the code writes, not what it reads,
# so it says nothing about the input data and is left out of the header.
_OUTPUT_PARTS = {"out", "output", "outputs", "dest", "destination", "target",
                 "save", "outfile"}


def starter_columns(source):
    """
    The column names for a starter data file: a list, empty when the
    functions take no arguments, or None when the code is given a file.

    The step people got stuck on after `--scaffold` was the data file: what
    goes in it, with a header or without. For code called with values, the
    answer is one column per named argument, named as the argument, which is
    also the name the reachability check looks for when an answer says `rate =
    100`. So the header is written for you, and only the rows, which have to
    be real, are left. Code that reads a file gets None: its data is a copy of
    such a file, and a header made up from argument names would be wrong.
    """
    names = []
    for fn in read_interface(source):
        a = fn.args
        for arg in a.posonlyargs + a.args + a.kwonlyargs:
            name = arg.arg
            if name in ("self", "cls"):
                continue
            parts = set(p for p in name.lower().split("_") if p)
            if parts & _FILE_PARTS:
                if parts & _OUTPUT_PARTS:
                    continue
                return None
            if name not in names:
                names.append(name)
    return names


def _source_rel(source_path, project_root):
    """The seed path as a task records it: relative when it can be, else absolute."""
    rel = _relative_to(source_path, project_root)
    return (rel if rel is not None else os.path.abspath(source_path)).replace(os.sep, "/")


def used_by(source_path):
    """
    The files beside `source_path` that import it, by name. cachetools'
    `_cached.py` is all private helpers, reached only through `__init__.py`.
    """
    import re

    folder = os.path.dirname(os.path.abspath(source_path))
    stem = os.path.splitext(os.path.basename(source_path))[0]
    pattern = re.compile(r"^\s*(from\s+\.%s\s+import|from\s+\.\s+import\s+.*\b%s\b|"
                         r"import\s+\S*\b%s\b)" % ((re.escape(stem),) * 3), re.M)
    out = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if not name.endswith(".py") or os.path.samefile(path, source_path):
            continue
        try:
            with open(path, encoding="utf-8-sig", errors="replace") as handle:
                if pattern.search(handle.read()):
                    out.append(name)
        except OSError:
            continue
    return out


def build_task(source_path, project_root, task_id=None, inputs=None, seed=None):
    """The task YAML text for one Python file, or a reason it cannot be built."""
    # utf-8-sig, not utf-8: Python runs a file that starts with a byte-order
    # mark, and Windows tools write one routinely (PowerShell 5.1's
    # `Set-Content -Encoding utf8`, older Notepad). Read as plain utf-8, the mark
    # survives as U+FEFF and ast.parse rejects a file Python itself accepts.
    with open(source_path, "r", encoding="utf-8-sig", errors="replace") as handle:
        source = handle.read()
    try:
        functions = read_interface(source)
    except SyntaxError as e:
        return None, f"{source_path} does not parse: {e}"
    if not functions:
        users = used_by(source_path)
        through = (f" Tests reach it through {', '.join(users)}, which imports it: "
                   f"scaffold that instead." if users else "")
        return None, (f"{source_path} has no public top level functions or classes, so "
                      f"there is no interface to describe. Tests need something to call."
                      + through)

    stem = os.path.splitext(os.path.basename(source_path))[0]
    if stem == "__init__":
        # A package's own code is named for the package, as
        # score_questions.task_for names it: MYPKG_VERIFY, not __INIT___VERIFY.
        stem = os.path.basename(os.path.dirname(os.path.abspath(source_path))) or stem
    base = task_id or "".join(c if c.isalnum() else "_" for c in stem).upper()
    # Named here, not by each caller, so `--scaffold` and the MCP tool cannot
    # disagree about what the task that tests existing code is called. Both
    # jobs share one data folder, since they read the same inputs.
    task_id = base + (VERIFY_SUFFIX if seed == "existing" else "")
    entry = guess_entrypoint(functions, stem)
    inputs = inputs or [f"inputs_private/data/{base}/input_01.csv"]

    fn_lines = "\n".join(
        f'    - "{_escaped(_signature(f))}  # TODO: what it does, e.g. reads one CSV and '
        f'returns its rows"' for f in functions)
    in_lines = "\n".join(f'  - "{p}"' for p in inputs)

    source_rel = _source_rel(source_path, project_root)
    if seed == "existing":
        name = os.path.basename(source_path)
        command = source_rel if " " not in source_rel else f'"{source_rel}"'
        # Marked, so nobody runs on it without reading it: the coding agent is
        # told this, and the line qikly can write is only a starting point.
        from qikly.score_questions import REQUIREMENT_MARK
        requirement = REQUIREMENT_MARK + default_requirement(source, name)
        return VERIFY_TEMPLATE.format(
            source_rel=source_rel, command=command, task_id=task_id, name=name,
            description=f"Tests for the existing {name}, from its owner's answers.",
            inputs=in_lines, module=module_path(source_path, task_id),
            functions="\n".join(f'    - "{_escaped(_signature(f))}"' for f in functions),
            entrypoint=_escaped(_signature(entry)), requirement=_quoted(requirement)), None
    seed_block = {
        None: SEED_NONE,
        "none": SEED_NONE,
        "existing": SEED_EXISTING.format(source_rel=source_rel),
    }[seed]

    return TASK_TEMPLATE.format(
        seed_block=seed_block,
        task_id=task_id,
        task_name=f"{task_id}: TODO one line summary, e.g. per-station daily temperature and humidity metrics",
        description="TODO: one paragraph on what this module is for, e.g. reads raw sensor CSVs, drops unusable readings, and writes one record per station per day",
        inputs=in_lines,
        module=module_path(source_path, task_id),
        functions=fn_lines,
        entrypoint=f"{_escaped(_signature(entry))}  # guessed, check this",
        source_rel=_source_rel(source_path, project_root),
    ), None


STARTER_TASK = '''# A starter task. Replace it, or copy it and edit.
#
# The two sections that matter are `requirements` and `acceptance_criteria`,
# and the difference between them is the whole design: the coding agent reads
# requirements and never reads acceptance_criteria, while test generation
# reads both. A criterion the agent could see is a criterion it can write code
# to satisfy without ever being tested on it.
#
# Decisions go in requirements: anything that could have gone another way, such
# as a threshold, a unit or an exemption, because the agent cannot guess it.
# Consequences go in acceptance_criteria: what must be true if those decisions
# are implemented correctly. If two careful developers could disagree about a
# line, it is a decision.
task_id: "MY_FIRST_TASK"

task_name: "My first task"

description: "Replace this with what the module is for."

inputs:
  - "inputs_private/data/MY_FIRST_TASK/input_01.csv"

outputs:
  - "outputs/data/MY_FIRST_TASK/output.json"

interface:
  module: "outputs.agent_src.code.MY_FIRST_TASK.pipeline"
  integration_functions:
    - "extract(input_path) -> list[dict]  # reads one input file"
    - "transform(rows) -> dict  # validates, returns {\\"accepted\\": [...], \\"rejected\\": [...]}"
    - "load(data, output_path) -> None  # writes the result as JSON"
  system_entrypoint: "run_pipeline(input_paths, output_path) -> None"

requirements:
  - "Read the input CSV and validate each row"
  - "A row is valid only if its identifier is non-empty and its quantity is a positive whole number"
  - "Write the result as JSON, keeping every valid row and every invalid row, and give each invalid row the reason it failed"

# Never shown to the coding agent. The consequences, with boundary values written out.
acceptance_criteria:
  - "A quantity of 0 is rejected and a quantity of 1 is accepted"
  - "A row with an empty identifier is rejected with a reason naming the field"
'''


def init_project(root, starter=True):
    """
    Create the directories and starter files a run needs. Never overwrites.

    `starter=False` leaves out MY_FIRST_TASK, for `--example`, which brings a
    finished task of its own. Handing someone both meant two tasks in their
    project on their first command, one of which nothing in the documentation
    mentioned, and a later bare `qikly` would have run the pair.
    """
    made, skipped = [], []
    dirs = [
        os.path.join(root, "inputs_private", "config", "tasks"),
        os.path.join(root, "outputs"),
    ]
    if starter:
        dirs.insert(1, os.path.join(root, "inputs_private", "data", "MY_FIRST_TASK"))
    for d in dirs:
        if os.path.isdir(d):
            skipped.append(d)
        else:
            os.makedirs(d, exist_ok=True)
            made.append(d)

    files = {
        os.path.join(root, "inputs_private", "config", "settings.yaml"):
            textwrap.dedent("""\
                # Your overrides. Anything absent falls back to the bundled defaults,
                # one top level section at a time, so you only state what you change.
                #
                # test_generation:
                #   criteria_per_batch: 4   # one generation call per 4 criteria
                #
                # agents:
                #   default:
                #     provider: gemini
                #     model: gemini-3.5-flash-lite
                """),
    }
    if starter:
        files[os.path.join(root, "inputs_private", "config", "tasks",
                           "MY_FIRST_TASK.yaml")] = STARTER_TASK
        files[os.path.join(root, "inputs_private", "data", "MY_FIRST_TASK",
                           "input_01.csv")] = (
            "identifier,quantity\nWIDGET-1,5\n,10\nWIDGET-2,0\n")

    for path, body in files.items():
        if os.path.exists(path):
            skipped.append(path)
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(body)
        made.append(path)
    return made, skipped


# The worked example ships in the wheel under inputs_public/examples/, laid out
# the way a real project is. Nothing copies it out on its own: it is not a
# bundled task, so ensure_task_data never sees it and the task loader never
# scans it. This map is the one route from the package into a project, and the
# destinations are exactly the paths the two task files already name, so the
# example runs the moment it lands.
#
# my_metrics.py goes to the project root rather than under inputs_private/
# because MY_METRICS_VERIFY.yaml records its seed as `implementation:
# "my_metrics.py"`, relative to the root. Put it anywhere else and the seeded
# task cannot find the code it is meant to test.
EXAMPLE_FILES = {
    ("config", "tasks", "MY_METRICS.yaml"):
        ("inputs_private", "config", "tasks", "MY_METRICS.yaml"),
    ("config", "tasks", "MY_METRICS_VERIFY.yaml"):
        ("inputs_private", "config", "tasks", "MY_METRICS_VERIFY.yaml"),
    ("data", "MY_METRICS", "input_01.csv"):
        ("inputs_private", "data", "MY_METRICS", "input_01.csv"),
    ("data", "MY_METRICS", "input_02.csv"):
        ("inputs_private", "data", "MY_METRICS", "input_02.csv"),
    ("reference", "MY_METRICS", "my_metrics.py"):
        ("my_metrics.py",),
}


def example_source_dir():
    """Where the shipped example lives inside the installed package."""
    from qikly.paths import PUBLIC_INPUTS_DIR

    return os.path.join(PUBLIC_INPUTS_DIR, "examples")


def install_example(root):
    """
    Copy the worked example into a project, at the paths its task files name.

    Same contract as init_project: never overwrites, and reports what it wrote
    and what it left alone. A reader who has already edited my_metrics.py keeps
    their version, and the run that follows tests theirs rather than ours.

    Returns (made, skipped, missing). `missing` is non-empty only if the wheel
    was built without the examples, which is reported rather than raised so a
    partial install is never left behind silently.
    """
    import shutil

    source_dir = example_source_dir()
    made, skipped, missing = [], [], []
    for source_parts, dest_parts in sorted(EXAMPLE_FILES.items()):
        source = os.path.join(source_dir, *source_parts)
        dest = os.path.join(root, *dest_parts)
        if not os.path.isfile(source):
            missing.append("/".join(source_parts))
            continue
        if os.path.exists(dest):
            skipped.append(dest)
            continue
        os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
        shutil.copyfile(source, dest)
        made.append(dest)
    return made, skipped, missing
